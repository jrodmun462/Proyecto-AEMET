SELECT A.ID_COMM, P.ID_PROV, P.NAM_PROV, m.nam_mun
FROM MUNICIPALITIES M
JOIN PROVINCE P ON P.ID_PROV = M.ID_PROV
JOIN AUT_COMM A ON A.ID_COMM = P.ID_COMM
WHERE NAM_COMM = 'Andalucía'
ORDER BY 3;

SELECT A.NAM_COMM, P.ID_PROV, MC.ID_PROV, MC.ID_CENTER, MC.NAM_CENTER
FROM METEOR_CENTER MC
JOIN PROVINCE P ON P.ID_PROV = MC.ID_PROV
JOIN AUT_COMM A ON A.ID_COMM = P.ID_COMM
WHERE A.NAM_COMM = 'Andalucía'
AND P.NAM_PROV = 'Almeria'
ORDER BY 5;